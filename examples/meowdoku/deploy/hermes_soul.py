"""Write an account's Hermes identity file (SOUL.md) from the profile text agent-day runs already get.

The text is produced by profile_prompt.main (the launcher's own resolver: profile choice, document order, job
additions, reduced guidance); nothing is resolved here. The decision tree is not copied: one line points the agent
at the SpeakToMe MCP. Regenerate at every launch; the file is generated and never hand-edited.

    python hermes_soul.py --accounts-db <accounts.db> --account gemma --hermes-home <dir>

Reads accounts.db directly (read access to the file, as profile_prompt.py has); no REST, no credentials.
"""
from __future__ import annotations

import argparse
import contextlib
import io
import os
import sys
import tempfile
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import profile_prompt  # noqa: E402

HEADER = "<!-- Generated by turing/examples/meowdoku/deploy/hermes_soul.py at every launch; do not edit. -->"
MCP_LINE = ("You walk your decisions through the SpeakToMe MCP (`enter map=decisions`) and read your orientation with "
            "`enter map=orientation` or `man`.")
SOUL_NAME = "SOUL.md"


def resolve_text(accounts_db, account, profile_id=None, instance_id=None, job=None):
    """The launcher's preamble for this account, or None when it has no character profile (profile_prompt exit 2)."""
    argv = ["--accounts-db", str(accounts_db), "--individual", account]
    if instance_id:
        argv += ["--instance-id", instance_id]
    elif profile_id:
        argv += ["--profile-id", profile_id]
    if job:
        argv += ["--job", job]
    out, failure = io.StringIO(), io.StringIO()
    saved = sys.stderr
    try:
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(failure):
            code = profile_prompt.main(argv)
    finally:
        sys.stderr = saved
    if code == 2:
        return None
    if code != 0:
        raise RuntimeError(f"profile resolution failed for {account} (exit {code}): {failure.getvalue().strip()}")
    return out.getvalue().rstrip("\n")


def render(text, account):
    # The launcher fills these placeholders per run; the ones that need a run ({reason}, {slot}) are not known here.
    text = (text.replace("{agent}", account).replace("{login}", account).replace("{account}", account)
            .replace("{now}", time.strftime("%Y-%m-%d %H:%M")))
    return f"{HEADER}\n\n{text}\n\n{MCP_LINE}\n"


def write_atomic(path, content):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    handle, temporary = tempfile.mkstemp(prefix=path.name + ".", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(handle, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(content)
        os.replace(temporary, path)
    except BaseException:
        with contextlib.suppress(OSError):
            os.unlink(temporary)
        raise


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--accounts-db", type=Path, required=True)
    parser.add_argument("--account", required=True)
    parser.add_argument("--hermes-home", type=Path, required=True)
    parser.add_argument("--profile-id")
    parser.add_argument("--instance-id")
    parser.add_argument("--job")
    args = parser.parse_args(argv)
    try:
        text = resolve_text(args.accounts_db, args.account, args.profile_id, args.instance_id, args.job)
    except RuntimeError as error:
        print(str(error), file=sys.stderr)
        return 1
    if text is None:
        print(f"no character profile exists for {args.account}", file=sys.stderr)
        return 2
    write_atomic(args.hermes_home / SOUL_NAME, render(text, args.account))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
