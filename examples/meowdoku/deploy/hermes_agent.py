"""Turn any SpeakToMe agent account into a Hermes agent ("the glove") and run one headless Hermes turn for it.

    python hermes_agent.py prepare --account gemma --provider custom --model gemma-4-26B-A4B-it-Q4_K_M --base-url http://127.0.0.1:11436/v1
    python hermes_agent.py run --account gemma --prompt "Call the whoami tool and say who you are."

prepare regenerates <hermes-root>/<account>/ every time: config.yaml, .env, plugins/speaktome (link to the
speaktome_hermes memory-provider package) and SOUL.md (via hermes_soul.py, not copied). Only the memory, todo and
SpeakToMe-MCP toolsets are ever enabled: no shell, file or web tools. Secrets stay in their files; only paths are written.
run starts `hermes chat -q` with HERMES_HOME set to that directory and kills the whole process tree at the timeout.
"""
from __future__ import annotations

import argparse
import contextlib
import os
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import hermes_soul  # noqa: E402

GENERATED = "Generated by turing/examples/meowdoku/deploy/hermes_agent.py (prepare) at every launch; do not edit."
PROVIDERS = ("custom", "anthropic", "openai", "gemini")
TOOLSETS = ("memory", "todo", "mcp-speaktome")  # the only toolsets ever written; nothing shell/file/web
DEFAULT_TOOLS = "whoami,where,look,enter,go,leave,examine,man,say,pending,acknowledge,contacts"
WORKSPACE = Path(r"C:\dev\Powershell") if os.name == "nt" else Path.home() / "Powershell"
DEFAULT_HERMES_ROOT = WORKSPACE / "srv" / "state" / "hermes"
DEFAULT_SPEAKTOME = WORKSPACE / "speaktome"
DEFAULT_SECRETS = WORKSPACE / "srv" / "state" / "secrets" / "operator_credentials"
DEFAULT_ACCOUNTS_DB = WORKSPACE / "srv" / "state" / "sql" / "accounts.db"
DEFAULT_PROGRAM = WORKSPACE / "srv" / "tools" / "hermes-agent" / "0.19.0" / "venv"
DEFAULT_BASE = "https://stichka.duckdns.org:8766"
TIMEOUT_EXIT = 124


def _program(program_dir):
    return Path(program_dir) / ("Scripts" if os.name == "nt" else "bin") / ("hermes.exe" if os.name == "nt" else "hermes")


def _venv_python(root):
    return Path(root) / ".venv" / ("Scripts" if os.name == "nt" else "bin") / ("python.exe" if os.name == "nt" else "python")


# ---- platform section: the only OS-specific code (directory link, process-tree kill) ----
def link_directory(link, target):
    link, target = Path(link), Path(target)
    if os.path.lexists(link):
        try:
            link.unlink()  # symlink
        except OSError:
            os.rmdir(link)  # Windows junction (removes the link, not the target)
    if os.name == "nt":
        result = subprocess.run(["cmd", "/c", "mklink", "/J", str(link), str(target)], capture_output=True, text=True)
        if result.returncode != 0:
            raise RuntimeError(f"junction {link} -> {target} failed: {result.stdout.strip()} {result.stderr.strip()}")
    else:
        os.symlink(target, link, target_is_directory=True)


def spawn_kwargs():
    return {"creationflags": subprocess.CREATE_NEW_PROCESS_GROUP} if os.name == "nt" else {"start_new_session": True}


def kill_tree(process):
    if os.name == "nt":
        subprocess.run(["taskkill", "/T", "/F", "/PID", str(process.pid)], capture_output=True)
    else:
        import signal
        with contextlib.suppress(ProcessLookupError):
            os.killpg(os.getpgid(process.pid), signal.SIGKILL)
    with contextlib.suppress(Exception):
        process.kill()
# ---- end platform section ----


def render_config(account, provider, model, base_url, secret_file, base, mcp_python, mcp_api, tools):
    if provider == "custom" and not base_url:
        raise SystemExit("--base-url is required for --provider custom")
    lines = [f"# {GENERATED}",
             f"# Hermes home for SpeakToMe account {account}. No shell, file or web tools: the agent acts through the SpeakToMe MCP.",
             "model:", f"  provider: {provider}"]
    if provider == "custom":
        lines.append(f"  base_url: {base_url}")
    lines.append(f"  default: {model}")
    if provider == "custom":
        lines += ["custom_providers:", "  - name: local-llama", f"    base_url: {base_url}", f"    model: {model}"]
    lines += ["memory:", "  provider: speaktome", "toolsets:"]
    lines += [f"  - {name}" for name in TOOLSETS]
    lines += ["mcp_servers:", "  speaktome:", f"    command: {mcp_python}", "    args:", f"      - {mcp_api}", "    env:",
              f"      SPEAKTOME_USER: {account}", f"      SPEAKTOME_SECRET_FILE: {secret_file}", f"      SPEAKTOME_BASE: {base}",
              "    tools:", f"      include: [{', '.join(tools)}]"]
    return "\n".join(lines) + "\n"


def render_env(account, secret_file, base, root):
    return (f"# {GENERATED}\n# Paths only; the secret stays in its file.\n"
            f"SPEAKTOME_BASE={base}\nSPEAKTOME_USER={account}\nSPEAKTOME_SECRET_FILE={secret_file}\nSPEAKTOME_ROOT={root}\n")


def prepare(args):
    home = Path(args.hermes_root) / args.account
    package = Path(args.speaktome_hermes)
    root = package.resolve().parent
    secret = Path(args.secrets_dir) / f"{args.account}.secret"
    tools = [item.strip() for item in args.tools_include.split(",") if item.strip()]
    mcp_python = args.mcp_python or _venv_python(DEFAULT_SPEAKTOME)
    mcp_api = args.mcp_api or DEFAULT_SPEAKTOME / "speaktome_mcp" / "api.py"
    config = render_config(args.account, args.provider, args.model, args.base_url, secret, args.speaktome_base,
                           mcp_python, mcp_api, tools)
    hermes_soul.write_atomic(home / "config.yaml", config)
    hermes_soul.write_atomic(home / ".env", render_env(args.account, secret, args.speaktome_base, root))
    (home / "plugins").mkdir(parents=True, exist_ok=True)
    link_directory(home / "plugins" / "speaktome", package)
    code = hermes_soul.main(["--accounts-db", str(args.accounts_db), "--account", args.account, "--hermes-home", str(home)])
    if code == 2:
        print(f"warning: {args.account} has no character profile; continuing without SOUL.md", file=sys.stderr)
    elif code != 0:
        print(f"warning: SOUL.md generation failed (exit {code}); continuing without it", file=sys.stderr)
    print(home)
    return 0


def run(args):
    home = Path(args.hermes_root) / args.account
    if not (home / "config.yaml").is_file():
        print(f"{home} is not prepared; run prepare first", file=sys.stderr)
        return 1
    exe = Path(args.hermes_exe) if args.hermes_exe else _program(args.program_dir)
    environment = dict(os.environ, HERMES_HOME=str(home), PYTHONUTF8="1")
    # Hermes loads context files (AGENTS.md, .hermes.md, .cursorrules) from its working directory: start it in the
    # account's own home so no repository's guidance becomes the agent's (2026-11-20: turing's AGENTS.md leaked in).
    process = subprocess.Popen([str(exe), "chat", "-q", args.prompt], env=environment, cwd=str(home), **spawn_kwargs())
    try:
        return process.wait(timeout=args.timeout_seconds)
    except subprocess.TimeoutExpired:
        kill_tree(process)
        process.wait()
        print(f"hermes timed out after {args.timeout_seconds}s; process tree killed", file=sys.stderr)
        return TIMEOUT_EXIT
    except KeyboardInterrupt:
        kill_tree(process)
        raise


def build_parser():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("prepare", "run"):
        item = sub.add_parser(name)
        item.add_argument("--account", required=True)
        item.add_argument("--hermes-root", type=Path, default=DEFAULT_HERMES_ROOT)
    p = sub.choices["prepare"]
    p.add_argument("--provider", choices=PROVIDERS, required=True)
    p.add_argument("--model", required=True)
    p.add_argument("--base-url")
    p.add_argument("--speaktome-hermes", type=Path, default=DEFAULT_SPEAKTOME / "speaktome_hermes")
    p.add_argument("--tools-include", default=DEFAULT_TOOLS)
    p.add_argument("--speaktome-base", default=DEFAULT_BASE)
    p.add_argument("--secrets-dir", type=Path, default=DEFAULT_SECRETS)
    p.add_argument("--accounts-db", type=Path, default=DEFAULT_ACCOUNTS_DB)
    p.add_argument("--mcp-python", type=Path, help="python for the SpeakToMe MCP server (default: live speaktome .venv)")
    p.add_argument("--mcp-api", type=Path, help="speaktome_mcp/api.py (default: live speaktome tree)")
    r = sub.choices["run"]
    r.add_argument("--prompt", required=True)
    r.add_argument("--timeout-seconds", type=float, default=900)
    r.add_argument("--program-dir", type=Path, default=DEFAULT_PROGRAM)
    r.add_argument("--hermes-exe", type=Path, help="override the hermes executable (tests)")
    return parser


def main(argv=None):
    args = build_parser().parse_args(argv)
    return prepare(args) if args.command == "prepare" else run(args)


if __name__ == "__main__":
    raise SystemExit(main())
