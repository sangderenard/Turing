def root(a: int, b: int) -> tuple[int, int]:
    # Python's floored ``//`` and ``%`` at the int64 edges: no intermediate
    # may leave int64 (``a - a % b`` does at -2**63 // 3 and
    # (2**63 - 1) // -2), and -2**63 % -1 is 0, not a trapped divide.
    return a // b, a % b

