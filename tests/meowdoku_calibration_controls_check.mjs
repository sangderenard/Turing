import assert from 'node:assert/strict';
import {initCalibration} from '../examples/meowdoku/web/marble_calibration.js';
const nodes=new Map();
const node=id=>{if(!nodes.has(id))nodes.set(id,{disabled:true,hidden:true,textContent:'',handlers:{},addEventListener(name,fn){this.handlers[name]=fn;}});return nodes.get(id);};
const doc={getElementById:node};
initCalibration(doc,{getGobos:()=>({gobos:[{artwork:{rectangles:[{id:'exposure-card'}]}}]})});
const watch=node('calibration-watch'),run=node('calibration-run'),upload=node('calibration-yaml-upload'),status=node('calibration-status');
await watch.handlers.click();
assert.match(status.textContent,/Set up 500 mock lux/);
node('calibration-exposure-preset').handlers.click();
assert.equal(watch.disabled,false);
assert.match(status.textContent,/No YAML upload is needed/);
upload.files=[{name:'dual.yaml',text:async()=> 'name: dual\ndual_camera: true\ncases:\n  - strength: 1500\n'}];
await upload.handlers.change();
assert.equal(watch.disabled,false);
assert.equal(run.disabled,false);
upload.files=[{name:'sweep.yaml',text:async()=> 'name: sweep\ncases:\n  - strength: 1500\n'}];
await upload.handlers.change();
assert.equal(watch.disabled,true);
assert.equal(run.disabled,false);
assert.match(status.textContent,/sweep-only/);
upload.files=[];
await upload.handlers.change();
assert.equal(watch.disabled,true);
assert.equal(run.disabled,true);
assert.match(status.textContent,/without a YAML file/);
console.log('Calibration setup/watch UI state passed; no network or renderer invoked');
