import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import vm from "node:vm";
const root = new URL("../", import.meta.url), load = path => readFileSync(new URL(path, root), "utf8");
const initial = JSON.parse(load("build/dot-studio-game-transfer-20261110/studio-building-definition-v2.json"));
const captured = JSON.parse(load("build/dot-studio-game-transfer-20261110/captured-studio-marble.json"));
const context = vm.createContext({structuredClone, Set, Map, mechanicalCreatureStudioBuildingDefinition: initial});
vm.runInContext(load("examples/meowdoku/web/mechanical_creature_studio_building.js"), context);
const originalBuilder = context.prepareMechanicalCreatureStudioBuilding;
let calls = 0;
context.prepareMechanicalCreatureStudioBuilding = (...args) => {calls++; return originalBuilder(...args);};
vm.runInContext(load("examples/meowdoku/web/mechanical_creature_studio_bridge.js"), context);
const result = context.mechanicalCreatureStudioBridge.prepareEnvironment(captured, {assetIdentity: "studio-scene:test-refresh"});
assert.equal(calls, 1, "uses existing lexical builder once, no copied geometry recipe");
assert.equal(result.definition.identity, initial.identity);
assert.equal(result.definition.assetIdentity, "studio-scene:test-refresh");
assert.equal(result.revision, captured.revision);
assert.deepEqual([...result.definition.translationM], initial.translationM);
assert.deepEqual([...result.building.placement], initial.placement);
assert.deepEqual([...result.building.proxyIds], initial.proxyIdentities);
assert.equal(result.building.entrance.widthM, initial.entrance.widthM);
assert.equal(result.building.entrance.heightM, initial.entrance.heightM);
assert.ok(result.definition.boxes.every(box => box.appearance.studio_asset_identity === result.assetIdentity));
assert.throws(() => context.mechanicalCreatureStudioBridge.prepareEnvironment(captured), /assetIdentity/);
console.log("PASS: fresh captured environment uses original builder, fixed registry placement/entrance and new explicit asset identity");
