import assert from "node:assert/strict";
import { marblePreviewSpec, livePreviewParticle, previewLawToScene, cameraNudgeGravity } from "../examples/meowdoku/web/marble_sim_preview.js";
import { decodeStart } from "../examples/meowdoku/web/compute.js";

const base={manifest:"fountain3d.manifest.json",size:"small",view:[-1,1,0,2],depth:1,
  uniforms:{grav_z:-9.8,emit_rate:0.02,r0:0.01,rho0:1}};
const physical={"sim-radius":0.012,"sim-rho":2,"sim-mu":0.45,"sim-e":0.3,"sim-roll":0.08,"sim-irr":0.04,"sim-omega":180};
const spec=marblePreviewSpec(base,physical,7);
assert.equal(spec.epoch,7);
assert.equal(spec.uniforms.r0,0.012);
assert.equal(spec.uniforms.rho0,2);
assert.equal(spec.uniforms.mu0,0.45);
assert.equal(spec.uniforms.omega,180);
assert.equal(spec.uniforms.emit_rate,1e9);
assert.equal(spec.uniforms.grav_z,-9.8);
assert.equal(base.uniforms.r0,0.01);
const ages=Buffer.alloc(8*4);
for(let id=2;id<8;id++)ages.writeFloatLE(-1e9,id*4);
const bounded=decodeStart({age_f32:ages.toString("base64")},8).age;
assert.deepEqual(Array.from(bounded.slice(0,3)),[0,0,-1e9]);
assert.throws(()=>decodeStart({age_f32:"AA=="},8),/initial age column/);
const multi=marblePreviewSpec({...base,studio_count:2,uniforms:{...base.uniforms,emit_rate:0.16},start:{age_f32:ages.toString("base64")}},physical,8);
assert.equal(multi.uniforms.emit_rate,0.16);
assert.ok(multi.start.age_f32);
assert.throws(()=>marblePreviewSpec(base,{...physical,"sim-rho":2600},8),/native law/);
assert.throws(()=>marblePreviewSpec(base,{...physical,"sim-omega":201},8),/native law/);
assert.equal(livePreviewParticle(new Float32Array([0,0,0,0,0])),null);
assert.deepEqual(livePreviewParticle(new Float32Array([1,2,3,0,120])),{x:1,y:2,z:3,radius:0.02});
assert.deepEqual(livePreviewParticle(new Float32Array([0,0,0,0,0,4,5,6,0,120]),1),{x:4,y:5,z:6,radius:0.02});
const map=previewLawToScene(base.view,base.depth,0.012);
assert.ok(map.point([0,1,0]).every((v)=>Math.abs(v)<1e-12));
assert.deepEqual(cameraNudgeGravity(0,0,0),[0,0,-1]);
const right=cameraNudgeGravity(1,0,0),up=cameraNudgeGravity(0,1,0);
assert.ok(right[0]>0.7 && right[1]===0 && up[1]>0.7);
const turned=cameraNudgeGravity(1,0,Math.PI/2);
assert.ok(Math.abs(turned[0])<1e-12 && turned[1]<-0.7);
assert.ok(Math.abs(Math.hypot(...turned)-1)<1e-12);
console.log("marble simulation preview: native field mapping and packed particle position");
